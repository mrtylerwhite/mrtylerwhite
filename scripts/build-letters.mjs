// Serve a .webp next to a .jpg/.png cover when one exists.
function coverWebp(src) {
  const webp = src.replace(/\.(jpe?g|png)$/i, ".webp");
  const hasWebp = webp !== src && src.startsWith("/") && fs.existsSync(path.join(ROOT, webp.slice(1)));
  return hasWebp ? webp : null;
}

function coverSmall(webp) {
  const small = webp.replace(/\.webp$/, "-800.webp");
  return fs.existsSync(path.join(ROOT, small.slice(1))) ? small : null;
}

function coverPicture(src, attrs) {
  const webp = coverWebp(src);
  const img = `<img src="${esc(src)}" ${attrs} />`;
  if (!webp) return img;
  const small = coverSmall(webp);
  const sizes = attrs.includes("letter__cover") ? "(max-width: 760px) 100vw, 728px" : "320px";
  const srcset = small ? `${esc(small)} 800w, ${esc(webp)} 1536w` : esc(webp);
  const sizesAttr = small ? ` sizes="${sizes}"` : "";
  return `<picture><source srcset="${srcset}"${sizesAttr} type="image/webp" />${img}</picture>`;
}

// Fetch the cover before the parser reaches the <img>, so it can be the first paint.
function coverPreload(src) {
  if (!src) return "";
  const webp = coverWebp(src);
  const small = webp && coverSmall(webp);
  if (small) {
    return `  <link rel="preload" as="image" imagesrcset="${esc(small)} 800w, ${esc(webp)} 1536w" imagesizes="(max-width: 760px) 100vw, 728px" type="image/webp" fetchpriority="high" />\n`;
  }
  const href = webp || src;
  const type = webp ? ' type="image/webp"' : "";
  return `  <link rel="preload" as="image" href="${esc(href)}"${type} fetchpriority="high" />\n`;
}
