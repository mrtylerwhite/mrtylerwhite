function rewriteCssUrls(css, base) {
  return css.replace(
    /url\(\s*(['"]?)(?!data:|https?:|\/)([^'")]+)\1\s*\)/g,
    (m, q, rel) => `url(${q}${new URL(rel, "https://x" + base).pathname}${q})`
  );
}
function readCssPart(file, base) {
  const css = fs.readFileSync(path.join(ROOT, file), "utf8").replace(/@import\s+url\([^)]+\)\s*;?/g, "");
  return `/* ${file} */\n${rewriteCssUrls(css, base)}`;
}
